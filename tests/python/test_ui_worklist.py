def _shipped(root: Path) -> set[str]:
    return {ln["id"] for ln in Store(root / "data").load("ui") if ln["status"] == "trusted"}


def test_every_worklist_key_is_translated_or_kept_with_a_proven_reason(root):
    listed = set(wago.read_keys(root / "pipeline/ui_keys.txt"))
    excluded = _exclusions(root)
    shipped = _shipped(root)
    undecided, unproven = [], []
    for group, keys in GROUPS.items():
        for key in keys:
            if key in listed:
                if key not in shipped:
                    undecided.append(f"{group} {key}: listed without a trusted Japanese line")
            elif key in excluded:
                if not _PROOF.search(excluded[key]):
                    unproven.append(f"{group} {key}: {excluded[key][:80]}")
            else:
                undecided.append(f"{group} {key}: neither listed nor excluded")
    assert undecided == [], undecided
    assert unproven == [], unproven


