"""The word frequency lists (`wfj.core.frequency`) and the files generated from them."""

from pathlib import Path

from wfj.core import frequency as fq

ADDON = Path("addon") / "WoWForeverJapanese"
MAX_GENERATED_BYTES = 3 * 1024 * 1024  # the lists are always in memory: a jump in size is looked at


def rec(*words, english=None):
    out = {"words": [list(w) for w in words]}
    if english:
        out["english"] = english
    return out


TAOSU = ("倒して", "たおして", "倒す", "たおす", "defeat")
TAOSHITA = ("倒した", "たおした", "倒す", "たおす", "defeated")
TEKI = ("敵", "てき", "敵", "てき", "enemy")
BARE = ("谷", "たに")


def test_a_word_is_counted_under_its_dictionary_form_and_reading_per_kind_of_text():
    current = {"quest": [rec(TAOSU, TEKI), rec(TAOSHITA)], "spell": [rec(TEKI, BARE)]}
    counts = fq.japanese_counts(current)
    assert counts["倒す\tたおす"] == [2, 0, 0, 0, 0, 0]
    assert counts["敵\tてき"] == [1, 0, 0, 0, 0, 1]
    assert counts["谷\tたに"] == [0, 0, 0, 0, 0, 1]
    assert sum(sum(c) for c in counts.values()) == 5  # every use of every word, once


def test_a_line_shipped_under_a_second_key_is_counted_once():
    line = rec(TAOSU, TEKI)
    current = {"quest": [line], "gossip": [line | {"id": "alias"}]}
    assert fq.japanese_counts(current) == {"倒す\tたおす": [1, 0, 0, 0, 0, 0], "敵\tてき": [1, 0, 0, 0, 0, 0]}


def test_the_ranking_is_most_used_first_then_by_key():
    counts = {"b\tb": [1, 1, 0, 0, 0, 0], "a\ta": [2, 0, 0, 0, 0, 0], "c\tc": [0, 0, 0, 0, 0, 9]}
    assert fq.ranked(counts) == ["c\tc", "a\ta", "b\tb"]
    assert fq.rows(counts)["c\tc"] == "0,0,0,0,0,9"


def test_an_english_word_is_counted_by_the_lines_that_list_it():
    current = {"quest": [rec(TAOSU, english="defeat=1 enemy=2"), rec(TEKI, english="enemy=1")]}
    counts = fq.english_counts(current, common=["hello"])
    assert counts["enemy"] == [2, 0, 0, 0, 0, 0]
    assert counts["defeat"] == [1, 0, 0, 0, 0, 0]
    assert counts["hello"] == [0, 0, 0, 0, 0, 0]


def test_the_rows_are_spread_over_files_by_their_key_alone():
    rows = {f"w{n}\tr": "1,0,0,0,0,0" for n in range(200)}
    spread = fq.shards(rows, 4)
    assert sum(len(part) for part in spread.values()) == 200
    assert fq.shards({"w7\tr": "x"}, 4).keys() <= spread.keys()
    assert next(iter(fq.shards({"w7\tr": "x"}, 4))) == next(k for k, part in spread.items() if "w7\tr" in part)


def test_a_grammar_line_must_be_a_word_of_the_list_and_listed_once(tmp_path):
    (tmp_path / fq.GRAMMAR_FILE).write_text(
        "# grammar\nだろう\tだろう\nだろう\tだろう\nない語\tないご\nbad line\n", encoding="utf-8"
    )
    keys, problems = fq.load_grammar(tmp_path, ["だろう\tだろう"])
    assert keys == ["だろう\tだろう"]
    assert len(problems) == 3
    assert "listed twice" in problems[0] and "not a word" in problems[1] and "word<TAB>reading" in problems[2]


def test_the_generated_frequency_files_stay_small(root):
    files = sorted((root / ADDON / "Data" / "Freq").glob("*.lua"))
    assert files, "Data/Freq/ is generated by `make generate`"
    assert sum(f.stat().st_size for f in files) < MAX_GENERATED_BYTES


def test_every_grammar_word_ships_and_is_a_row_of_the_japanese_list(root):
    text = "".join(f.read_text("utf-8") for f in sorted((root / ADDON / "Data" / "Freq").glob("Freq_ja_*.lua")))
    grammar = (root / ADDON / "Data" / "Freq" / "Freq_grammar.lua").read_text("utf-8")
    listed = [
        ln.split("#", 1)[0].rstrip()
        for ln in (root / "pipeline" / fq.GRAMMAR_FILE).read_text("utf-8").splitlines()
        if ln.split("#", 1)[0].strip()
    ]
    assert len(listed) >= 40
    for key in listed:
        lua = '["' + key.replace("\t", "\\t") + '"]'
        assert lua in text, key
        assert lua in grammar, key


def test_the_word_status_settings_all_sit_under_marks(root):
    # the word list's own group (`words.`) holds the save click and the screenshot, and nothing of word status
    elsewhere = ("words.plusOne", "words.learnNext", "words.statusMarks", "words.highlight", "words.score")
    hits = [
        f"{path.relative_to(root)}: {name}"
        for path in sorted((root / ADDON).rglob("*.lua"))
        if "Data" not in path.relative_to(root / ADDON).parts
        for name in elsewhere
        if name in path.read_text("utf-8")
    ]
    assert hits == []
