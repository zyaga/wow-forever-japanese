"""The voice addons' own files (ADR-061, ADR-062). Deterministic text.

A pack folder holds its TOC, Register.lua, README.txt and Sound/; the entry folder (the one a player
installs, which names every pack as a required dependency on CurseForge) holds only its TOC and README.txt.

The pack depends on the main addon and hands it one table through the main addon's single global,
`WoWForeverJapanese_RegisterVoice`. Format 3 (ADR-090): each line is { false, Japanese hash, s = { { file
name, seconds }, ... }, m = timing, v = { [voice id] = { false, s = {...}, m = timing } } }: the line in
one file per sentence, played one after another, and when each part of its Japanese is spoken
(core/voice_timing); the `v` table only for a line several differently cast creatures say (ADR-062);
`creatures` maps each speaker of such a line to its voice id ({ male voice, female voice } for a creature
shown as both). The addon plays a line only when the hash equals the hash of the Japanese it ships. An
addon too old to read format 3 takes none of the pack's lines, and the pack says so once at login.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

from wfj.emit.lua_writer import lua_string

FOLDER = "WoWForeverJapanese_Voice"
FORMAT = 3
VERSION = "0.0.1-mvp"
TITLE = "WoW Forever Japanese Voice (日本語音声)"
# the main addon's 字 medallion, so the voice rows nested under it in the AddOn List carry the same icon
ICON = "Interface\\AddOns\\WoWForeverJapanese\\Media\\icon"


def toc_text(
    interface: str,
    credits: Mapping[str, str] | None,
    title: str = TITLE,
    version: str = VERSION,
    project_id: int = 0,
) -> str:
    """A pack's TOC (with `credits`, it loads Register.lua) or the entry's (`credits` None: it loads
    Packs.lua, the list of its packs). The dependency on the main addon only orders loading: installing voice
    never installs the main addon."""
    if credits:
        # English only: the AddOn List tooltip font has no Japanese glyphs
        notes = (
            "Japanese voice for WoW Forever Japanese. The speech engine, the voices and their licences "
            "are listed in this addon's README.txt."
        )
    else:
        notes = "Japanese voice for WoW Forever Japanese: installs every voice pack. No audio of its own."
    head = [
        f"## Interface: {interface}",
        f"## Title: {title}",
        f"## Notes: {notes}",
        f"## IconTexture: {ICON}",
        "## Dependencies: WoWForeverJapanese",
        "## Author: Zyaga",
        f"## Version: {version}",
    ]
    if project_id:
        head.append(f"## X-Curse-Project-ID: {project_id}")
    return "\n".join([*head, "", "Register.lua" if credits else "Packs.lua", ""])


def entry_packs_text(folders: Sequence[str]) -> str:
    """The entry's Packs.lua: the folders of the packs it installs, so the addon can name one that did not
    load."""
    return "\n".join([
        "-- Generated by wfj voice pack. Do not edit.",
        "if not WoWForeverJapanese_ExpectVoicePacks then return end",
        "WoWForeverJapanese_ExpectVoicePacks({",
        *(f"  {lua_string(f)}," for f in folders),
        "})",
        "",
    ])


def _sentences(pieces: Sequence[tuple[str, float]], timing: str | None) -> str:
    files = ", ".join(f"{{ {lua_string(f)}, {s:.3f} }}" for f, s in pieces)
    return f"s = {{ {files} }}" + (f", m = {lua_string(timing)}" if timing else "")


def _line(key: str, e: Mapping[str, Any]) -> str:
    head = f"false, {lua_string(e['hash'])}, {_sentences(e['s'], e.get('m'))}"
    if not e.get("vs"):
        return f"    [{lua_string(key)}] = {{ {head} }},"
    v = ", ".join(
        f"[{lua_string(vid)}] = {{ false, {_sentences(pieces, timing)} }}"
        for vid, (pieces, timing) in sorted(e["vs"].items())
    )
    return f"    [{lua_string(key)}] = {{ {head}, v = {{ {v} }} }},"


def _creature(c: int, v: str | tuple[str, str]) -> str:
    if isinstance(v, tuple):
        return f"    [{c}] = {{ {lua_string(v[0])}, {lua_string(v[1])} }},"
    return f"    [{c}] = {lua_string(v)},"


def _errors(errors: Mapping[str, Any]) -> list[str]:
    if not errors:
        return []
    kinds = [f"      [{e}] = {lua_string(k)}," for e, k in sorted(errors["kinds"].items())]
    voices = []
    for who, files in sorted(errors["voices"].items()):
        voices.append(f"      [{lua_string(who)}] = {{")
        voices += [
            f"        [{lua_string(k)}] = {{ {lua_string(f)}, {s:.1f} }},"
            for k, (f, s) in sorted(files.items())
        ]
        voices.append("      },")
    return ["  errors = {", "    kinds = {", *kinds, "    },", "    voices = {", *voices, "    },", "  },"]


def register_text(
    lines: Mapping[str, Mapping[str, Any]],
    creatures: Mapping[int, Any] | None = None,
    errors: Mapping[str, Any] | None = None,
    folder: str = FOLDER,
) -> str:
    """`lines`: {pack key: {hash, s: [(file, seconds)], m: timing, vs: {voice id: ([(file, seconds)],
    timing)}}}; `creatures`:
    {creature id: voice id or (male, female)}; `errors`: {kinds: {game voice id: kind}, voices:
    {"<race>-<f|m>": {kind: (file, seconds)}}}, the character's own spoken error lines. Written sorted."""
    body = [_line(key, e) for key, e in sorted(lines.items())]
    who = [_creature(c, v) for c, v in sorted((creatures or {}).items())]
    return "\n".join(
        [
            "-- Generated by wfj voice pack. Do not edit.",
            "-- A main addon too old to read packs has no register function: the pack then stays silent.",
            "if not WoWForeverJapanese_RegisterVoice then return end",
            "local taken = WoWForeverJapanese_RegisterVoice({",
            f"  format = {FORMAT},",
            f"  folder = {lua_string(folder)},",
            "  lines = {",
            *body,
            "  },",
            "  creatures = {",
            *who,
            "  },",
            *_errors(errors or {}),
            "})",
            *(_too_old(folder) if lines else []),
            "",
        ]
    )


def _too_old(folder: str) -> list[str]:
    """An addon too old to read this format takes no line: the pack says so once, at login."""
    return [
        "if (taken or 0) == 0 then",
        "  local meta = (C_AddOns and C_AddOns.GetAddOnMetadata) or GetAddOnMetadata",
        f"  local title = meta and meta({lua_string(folder)}, \"Title\") or {lua_string(folder)}",
        f"  local version = meta and meta({lua_string(folder)}, \"Version\") or \"\"",
        "  local f = CreateFrame(\"Frame\")",
        "  f:RegisterEvent(\"PLAYER_LOGIN\")",
        "  f:SetScript(\"OnEvent\", function()",
        "    print(\"WFJ: \" .. title .. \" \" .. version .. \" needs a newer WoW Forever Japanese.\""
        " .. \" Update it in the CurseForge app.\")",
        "  end)",
        "end",
    ]


def readme_text(
    credits: Mapping[str, str], count: int, title: str = "WoW Forever Japanese Voice", holds: str = ""
) -> str:
    return "\n".join(
        [
            title,
            "",
            "Japanese voice over for the WoW Forever Japanese addon, which it needs to play anything.",
            *([holds] if holds else []),
            f"It holds {count} lines, spoken from the addon's own Japanese.",
            "",
            "Credits",
            f"- Speech engine: {credits['engine']}",
            f"- Voices: {credits['models']}",
            f"- Licences: {credits['licence']}",
            "",
            "The maintainer ran the speech engine on their own computer and on rented GPUs. "
            "No hosted speech service was used.",
            "",
        ]
    )


def entry_readme_text(title: str, packs: Sequence[tuple[str, str]]) -> str:
    """`packs`: (title, what it holds) of every pack the entry installs."""
    return "\n".join(
        [
            title,
            "",
            "Japanese voice over for the WoW Forever Japanese addon, which it needs to play anything.",
            "This addon holds no audio. Installing it from the CurseForge app installs every voice pack:",
            "",
            *(f"- {t}: {h}" for t, h in packs),
            "",
            "One setting in the addon's options turns the voice off.",
            "Removing these addons leaves the addon working.",
            "",
        ]
    )
