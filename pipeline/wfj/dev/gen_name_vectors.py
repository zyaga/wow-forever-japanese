"""Generate vectors/name_vectors.{jsonl,lua}: the shared contract between core/names.py and Core/Names.lua.

Three kinds of row, all taken from the committed data so the two sides are held to real names and real lines:
  hash  {en, key}             an English name and the key its Japanese is stored under
  name  {key, row}            a generated name row ("Japanese<TAB>reading") the line cases need
  line  {id, ja, out, html}   a shipped Japanese line and the same line with its names in Japanese
Usage: python -m wfj.dev.gen_name_vectors [out_dir]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from wfj.cmd.names import prose_lines
from wfj.core import markup, names
from wfj.emit.lua_writer import lua_string
from wfj.io.names_store import load_lines

HASHES, LINES = 240, 320
# Shapes every hash sample must hold at least one of: the client writes names all of these ways.
SHAPES = {
    "apostrophe": lambda en: "'" in en,
    "digit": lambda en: any(c.isdigit() for c in en),
    "the": lambda en: en.startswith("The "),
    "suffix": lambda en: en.startswith("of "),
    "hyphen": lambda en: "-" in en,
    "comma": lambda en: "," in en,
}


def _spread(items: list[Any], count: int) -> list[Any]:
    """`count` items evenly spaced over `items`, which is already in a fixed order."""
    if len(items) <= count:
        return items
    return [items[i * len(items) // count] for i in range(count)]


def _html(key: str, ja: str) -> bool:
    return key.startswith("book:") and markup.is_html_page(ja)


def build(root: Path) -> list[dict[str, Any]]:
    trusted = [ln for ln in load_lines(root) if ln["status"] == "trusted"]
    trusted.sort(key=lambda ln: ln["id"])
    by_en = {ln["en"]: ln for ln in trusted}
    picked = {ln["en"]: ln for ln in _spread(trusted, HASHES)}
    for test in SHAPES.values():
        for ln in _spread([ln for ln in trusted if test(ln["en"])], 4):
            picked[ln["en"]] = ln
    in_order = sorted(picked, key=lambda en: picked[en]["id"])
    rows: list[dict[str, Any]] = [{"t": "hash", "en": en, "key": names.name_id(en)} for en in in_order]

    def lookup(run: str) -> str | None:
        ln = by_en.get(run)
        return ln["ja"] if ln else None

    with_names = [(key, ja) for key, ja in sorted(prose_lines(root).items()) if names.latin_runs(ja)]
    used: dict[str, str] = {}
    lines = []
    pages = [(key, ja) for key, ja in with_names if _html(key, ja)]
    for key, ja in sorted({*_spread(with_names, LINES), *_spread(pages, 6)}):
        html = _html(key, ja)
        for run in names.latin_runs(ja):
            if run in by_en:
                used[by_en[run]["id"]] = f"{by_en[run]['ja']}\t{by_en[run]['reading']}"
        out = names.replace_runs(ja, lookup, html=html)
        lines.append({"t": "line", "id": key, "ja": ja, "out": out, "html": html})
    rows.extend({"t": "name", "key": k, "row": v} for k, v in sorted(used.items()))
    rows.extend(lines)
    return rows


def to_lua(rows: list[dict[str, Any]]) -> str:
    out = ["-- GENERATED by pipeline/wfj/dev/gen_name_vectors.py from data/. Do not edit.", "return {"]
    out.append("  hashes = {")
    for r in rows:
        if r["t"] == "hash":
            out.append(f"    {{ en = {lua_string(r['en'])}, key = {lua_string(r['key'])} }},")
    out.append("  },")
    out.append("  names = {")
    out.extend(f"    [{lua_string(r['key'])}] = {lua_string(r['row'])}," for r in rows if r["t"] == "name")
    out.append("  },")
    out.append("  lines = {")
    out.extend(
        f"    {{ id = {lua_string(r['id'])}, html = {'true' if r['html'] else 'false'},\n"
        f"      ja = {lua_string(r['ja'])},\n      out = {lua_string(r['out'])} }},"
        for r in rows
        if r["t"] == "line"
    )
    out.append("  },")
    out.append("}")
    return "\n".join(out) + "\n"


def write(root: Path, out_dir: Path) -> int:
    rows = build(root)
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "name_vectors.jsonl").open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    (out_dir / "name_vectors.lua").write_text(to_lua(rows), encoding="utf-8")
    return len(rows)


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    root = Path(__file__).resolve().parents[3]
    out = Path(args[0]) if args else root / "vectors"
    n = write(root / "data", out)
    print(f"wrote {out / 'name_vectors.jsonl'} and .lua ({n} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
