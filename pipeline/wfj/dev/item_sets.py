"""The item sets and their bonus spells, from a local install: the input of the set bonus lines.

    python -m wfj.dev.item_sets --wow "<client folder>" [--product wow_classic_beta] > pipeline/item_sets.txt
                                                                                        (make item-sets)

An item tooltip's "Set: <bonus>" line is the description of the set's bonus spell (ItemSetSpell.SpellID),
printed by the compiled client; `wfj generate` turns this file into the addon's set map (Data/ItemSets.lua):
item id → set id, set id → the bonus spells in threshold order, so the addon can show the line through that
spell's shipped Japanese. One line per set:
`<set id>\\t<name>\\t<item ids, comma-joined>\\t<spell id:threshold,
comma-joined, threshold then id order>`. The name is for reading the file only; it is never shipped.

Reads ItemSet (5 fields: Name_lang, SetFlags, RequiredSkill, RequiredSkillRank, ItemID[17]) and ItemSetSpell
(4 fields: ChrSpecID, SpellID, TraitSubTreeID, Threshold in the low byte; ItemSetID in the relationship map)
from the archive, never writes there (pipeline tooling only reads the game folder, ADR-021). Both maps were
checked on 1.60.1.70338 against wago.tools' export of the same build: every one of the 536 ItemSet rows and
1,477 ItemSetSpell rows matched, column for column. A changed layout hash stops the run with both hashes
named, so a moved field is never read as the wrong column. Neither table has ever carried a hotfix row on
Forever, so the hotfix cache is not read.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from wfj.io import casc, db2

# FileDataIDs from the community listfile: the root of this client carries no name hashes for them
TABLES = {"ItemSet": 1343609, "ItemSetSpell": 1314689}
LAYOUTS = {"ItemSet": (0xF79068A4, 5), "ItemSetSpell": (0x2666A73F, 4)}
HEADER = ("# GENERATED by `python -m wfj.dev.item_sets` from the installed client's ItemSet and ItemSetSpell"
          " tables.")


def _table(archive: casc.LocalArchive, name: str, strings: frozenset[int]) -> db2.Db2Table:
    fdid = archive.file_data_id(f"DBFilesClient\\{name}.db2", fallback=TABLES[name])
    buf, gaps = archive.read_file(fdid)
    header = db2.read_header(buf, name)
    want = LAYOUTS[name]
    if (header.layout_hash, header.field_count) != want:
        raise db2.Db2Error(
            f"{name}: layout hash {header.layout_hash:08x}/{header.field_count}f, "
            "the column map was verified "
            f"on {want[0]:08x}/{want[1]}f; re-verify the columns before reading this build"
        )
    return db2.read(buf, strings, gaps, name=name)


def rows(archive: casc.LocalArchive) -> list[str]:
    """One text line per set with items, sorted by set id."""
    sets = _table(archive, "ItemSet", frozenset({0}))
    spells = _table(archive, "ItemSetSpell", frozenset())
    by_set: dict[int, list[tuple[int, int]]] = {}
    for rid, v in spells.rows.items():
        set_id = spells.relation.get(rid)
        if set_id is not None:
            by_set.setdefault(set_id, []).append((v[3] & 0xFF, v[1]))
    out = []
    for set_id in sorted(sets.rows):
        name, _flags, _skill, _rank, items = sets.rows[set_id]
        item_ids = [i for i in items if i]
        if not item_ids:
            continue
        bonuses = ",".join(f"{spell}:{threshold}" for threshold, spell in sorted(by_set.get(set_id, [])))
        out.append(f"{set_id}\t{name}\t{','.join(str(i) for i in item_ids)}\t{bonuses}")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="wfj.dev.item_sets", description=__doc__.split("\n\n")[0])
    ap.add_argument("--wow", required=True, type=Path, help="the client folder holding .build.info")
    ap.add_argument("--product", default="wow_classic_beta", help=".build.info product")
    args = ap.parse_args(argv)
    try:
        archive = casc.LocalArchive(args.wow, args.product)
        lines = rows(archive)
    except (casc.CascError, db2.Db2Error) as e:
        print(f"item-sets: {e}", file=sys.stderr)
        return 1
    print(HEADER)
    print(f"# build {archive.info.version}: {len(lines)} sets with items; "
          "set id, name, item ids, spell id:threshold")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
